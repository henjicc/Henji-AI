/**
 * 项目卡片网格的横向布局：列数由可用宽度算出，不写断点（设计稿 CanvasProjects，界面重设计 3.3）。
 *
 * 这几个值必须放在一起改——列数上限是靠"限制可用宽度"反推出来的，
 * CSS 的 auto-fill 没有"最多几列"的写法。三个数（最小卡宽 / 列间距 / 最大宽度）互相绑死。
 */

/** 网格自身的列定义与间距（列 20、行 28）。`min(15rem,100%)` 保证窗口窄于一张卡时不横向溢出。 */
export const PROJECT_GRID_COLUMNS_CLASS = 'grid-cols-[repeat(auto-fill,minmax(min(15rem,100%),1fr))] gap-x-5 gap-y-7';

/**
 * 内容区最大宽度：**列数上限 4 就是靠这个数实现的**（设计稿页面最大宽 1200、左右各留 40）。
 *
 *   列数 = floor((可用宽 + 列间距) / (最小卡宽 + 列间距))
 *   70rem = 1120px：floor((1120 + 20) / (240 + 20)) = 4，每张卡约 265px；
 *   960 窗口下可用宽约 912px → 3 列。
 *
 * 更宽的窗口两侧留白，不再加列。标题区与网格共用这个宽度，
 * 否则宽屏上「新建」按钮会飞到网格右边之外。
 */
export const PROJECT_GRID_MAX_WIDTH_CLASS = 'max-w-[70rem]';
