/*
 * 口播成片的目标节奏：两个保留的字之间留多长的停顿。只有这一处定义。
 *
 * 粗剪分几步下刀（去重念、压缩停顿、删呼吸、清气口），每一步都要回答“这里留多长”。各自定一个数时，
 * 前面的步骤留得比最后一步的目标还短，最后一步就补不回来（只缩短、不拉长），同一类位置的停顿于是长短不一。
 * 所以：去重念落刀时至少留这么长，最后由气口清理（gaps.ts）把更长的收到这个长度。
 * 这是上限，不是保证：气口清理只缩不放。删呼吸那一步有自己的下限（breaths.ts：句末与接缝 150 毫秒、句中 80 毫秒，
 * 意思是“删掉这口气之后两个字会不会粘住”），不够这么长才垫一截减弱的呼吸；所以删过呼吸的句末停顿最后落在 150–200 毫秒之间，
 * 不一定正好是这里的数。压缩长停顿留下的（设置里的保留时长，默认更长）同样由气口清理收到这里。
 *
 * 取值依据是用户改定的口播（评估台的定稿用例）。那份定稿是在这两个数的基础上手改出来的，所以依据是“用户没有去动它们”：
 * - 句末与重念接缝 200 毫秒：定稿里缩短过的 36 处句末停顿有 27 处仍是 200；25 处落在句末标点上的接缝中位数也是 200；
 * - 分句（逗号、顿号、冒号）与句中明显的停顿 120 毫秒：定稿里缩短过的 42 处分句停顿有 26 处仍是 120。
 * 用户偏快节奏，这两个数已经是偏短的一档；定稿里把它们再调短或调长的各只有几处，没有一致的方向，不再细分。
 * 落在逗号上的接缝是否该用分句的长度：定稿里这类接缝 25 处，一半留 200、7 处短于 120，按哪个数都有七处差得远，仍按接缝算。
 */
