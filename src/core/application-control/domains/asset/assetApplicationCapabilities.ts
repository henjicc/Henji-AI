import { z } from 'zod'
import { importLocalMediaCapability } from './localMediaImportCapability'
import { recognizeDocumentTextCapability } from './documentTextCapability'
import { APP_STORE_ICON_CAPABILITIES } from './appStoreIconCapabilities'

import type { ApplicationCapabilityDefinition } from '../../applicationCapabilities'
import {
  capabilityControl,
  capabilityOutputSchema,
  defineApplicationCapability,
} from '../shared/defineApplicationCapability'

const queryAssets = defineApplicationCapability({
  id: 'query_assets',
  version: 1,
  title: '查询素材库',
  description: '按媒体类型、标签、集合和关键词分页查询素材摘要，不返回本地文件路径。',
  domain: 'assets',
  aliases: ['查找素材', '素材库', '搜索图片', 'search assets'],
  readOnly: true,
  control: capabilityControl('observe', ['asset']),
  dataClasses: ['C1'],
  idempotent: true,
  destructive: false,
  timeoutMs: 8_000,
  supportsPreview: false,
  supportsUndo: false,
  requiredScopes: [],
  producesRefs: ['asset'],
  inputSchema: z.object({
    mediaType: z.enum(['image', 'video', 'audio', 'code']).optional(),
    libraryId: z.string().min(1).optional(),
    tag: z.string().min(1).optional(),
    keyword: z.string().max(200).optional(),
    page: z.number().int().min(1).max(1_000).default(1),
    pageSize: z.number().int().min(1).max(50).default(20),
    sort: z.enum(['created', 'recent']).default('created'),
  }).strict(),
  outputSchema: capabilityOutputSchema({
    items: z.array(z.record(z.string(), z.unknown())),
    total: z.number(),
    page: z.number(),
    pageSize: z.number(),
  }),
  concurrencyKey: 'assets_query',
  resolveTargetIds: (input) => ({
    keyword: input.keyword ?? '',
    libraryId: input.libraryId ?? '',
  }),
  summarize: (output) => `素材库返回 ${output.items.length} 项。`,
})

const getAsset = defineApplicationCapability({
  id: 'get_asset',
  version: 1,
  title: '读取素材详情',
  description: '按稳定素材引用读取元数据、标签和集合信息。',
  domain: 'assets',
  aliases: ['素材详情', '这张素材', '读取图片素材', 'get asset'],
  readOnly: true,
  control: capabilityControl('observe', ['asset']),
  dataClasses: ['C1'],
  idempotent: true,
  destructive: false,
  timeoutMs: 5_000,
  supportsPreview: false,
  supportsUndo: false,
  requiredScopes: [],
  acceptsRefs: ['asset'],
  producesRefs: ['asset'],
  inputSchema: z.object({ assetId: z.string().min(1) }).strict(),
  outputSchema: capabilityOutputSchema({
    asset: z.record(z.string(), z.unknown()),
  }),
  concurrencyKey: 'asset',
  resolveConcurrencyKey: (input) => `asset:${input.assetId}`,
  resolveTargetIds: (input) => ({ assetId: input.assetId }),
  summarize: (output) => `已读取素材 ${String(output.asset.id ?? '')}。`,
})

