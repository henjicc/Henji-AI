function defineAssetLibraryMembershipCapability(
  id: 'add_asset_to_library' | 'remove_asset_from_library',
  status: 'added' | 'removed'
): ApplicationCapabilityDefinition {
  const adding = status === 'added'
  return defineApplicationCapability({
    id,
    version: 1,
    title: adding ? '添加素材到集合' : '从集合移除素材',
    description: adding
      ? '把明确素材加入指定集合。'
      : '从指定集合移除明确素材，不删除素材本身。',
    domain: 'assets',
    aliases: adding ? ['加入素材集合', 'add asset to library'] : ['移出素材集合', 'remove asset from library'],
    readOnly: false,
    risk: 'R1',
    dataClasses: ['C1'],
    permission: 'assets:write',
    idempotent: true,
    destructive: false,
    timeoutMs: 8_000,
    supportsPreview: false,
    supportsUndo: false,
    requiredScopes: ['assets'],
    acceptsRefs: ['asset', 'asset.library'],
    producesRefs: ['asset', 'asset.library'],
    inputSchema: z.object({
      libraryId: z.string().min(1),
      assetId: z.string().min(1),
    }).strict(),
    outputSchema: capabilityOutputSchema({
      libraryId: z.string(),
      assetId: z.string(),
      status: z.literal(status),
    }),
    concurrencyKey: 'asset_library',
    resolveConcurrencyKey: (input) => `library:${input.libraryId}`,
    resolveTargetIds: (input) => ({
      libraryId: input.libraryId,
      assetId: input.assetId,
    }),
    summarize: (output) => adding
      ? `素材 ${String(output.assetId)} 已加入集合。`
      : `素材 ${String(output.assetId)} 已从集合移除。`,
  })
}

