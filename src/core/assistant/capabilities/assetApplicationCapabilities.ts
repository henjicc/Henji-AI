import { z } from 'zod'

import type { ApplicationCapabilityDefinition } from '../applicationCapabilities'
import {
  capabilityOutputSchema,
  defineApplicationCapability,
} from './defineApplicationCapability'

const queryAssets = defineApplicationCapability({
  id: 'query_assets',
  version: 1,
  title: '查询素材库',
  description: '按媒体类型、标签、集合和关键词分页查询素材摘要，不返回本地文件路径。',
  domain: 'assets',
  aliases: ['查找素材', '素材库', '搜索图片', 'search assets'],
  readOnly: true,
  risk: 'R0',
  dataClasses: ['C1'],
  permission: 'assets:read',
  idempotent: true,
  destructive: false,
  timeoutMs: 8_000,
  supportsPreview: false,
  supportsUndo: false,
  requiredScopes: [],
  producesRefs: ['asset'],
  inputSchema: z.object({
    mediaType: z.enum(['image', 'video', 'audio']).optional(),
    libraryId: z.string().min(1).optional(),
    tag: z.string().min(1).optional(),
    keyword: z.string().max(200).optional(),
    page: z.number().int().min(1).max(1_000).default(1),
    pageSize: z.number().int().min(1).max(50).default(20),
    sort: z.enum(['created', 'recent']).default('created'),
  }).strict(),
  outputSchema: capabilityOutputSchema({
    items: z.array(z.record(z.string(), z.unknown())),
    total: z.number(),
    page: z.number(),
    pageSize: z.number(),
  }),
  concurrencyKey: 'assets_query',
  resolveTargetIds: (input) => ({
    keyword: input.keyword ?? '',
    libraryId: input.libraryId ?? '',
  }),
  summarize: (output) => `素材库返回 ${output.items.length} 项。`,
})

